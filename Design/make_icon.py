#!/usr/bin/env python3
"""Generates AppIcon.svg and renders the app icon PNG.

Usage (from the repo root or this folder):
    python3 Design/make_icon.py
Needs rsvg-convert and ImageMagick's convert (to drop the alpha channel,
which App Store icons must not have).
"""
import math
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
PNG = os.path.join(HERE, "..", "TimeTrack", "Assets.xcassets", "AppIcon.appiconset", "AppIcon.png")

cx, cy, R = 620, 470, 290       # tyre centre and outer radius
ground = cy + R                 # y of the bottom tip, where the tyre touches the ground
rim_r, face_r = 200, 182        # rim and clock face radii


def tread_grooves():
    # Slanted grooves that stay inside the tyre's edge (a directional tread).
    out = []
    for i in range(30):
        a = math.radians(i * 12)
        r1, r2 = R - 54, R - 14
        da = math.radians(4)
        x1, y1 = cx + r1 * math.cos(a), cy + r1 * math.sin(a)
        x2, y2 = cx + r2 * math.cos(a + da), cy + r2 * math.sin(a + da)
        out.append(f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}"/>')
    return "\n    ".join(out)


def clock_ticks():
    out = []
    for i in range(12):
        a = math.radians(i * 30 - 90)
        major = i % 3 == 0
        r1 = face_r - (44 if major else 28)
        r2 = face_r - 14
        out.append(
            f'<line x1="{cx + r1 * math.cos(a):.1f}" y1="{cy + r1 * math.sin(a):.1f}" '
            f'x2="{cx + r2 * math.cos(a):.1f}" y2="{cy + r2 * math.sin(a):.1f}" '
            f'stroke-width="{16 if major else 9}"/>')
    return "\n    ".join(out)


def hand(angle_deg, length, width):
    a = math.radians(angle_deg - 90)
    return (f'<line x1="{cx}" y1="{cy}" x2="{cx + length * math.cos(a):.1f}" '
            f'y2="{cy + length * math.sin(a):.1f}" stroke="#1B2530" '
            f'stroke-width="{width}" stroke-linecap="round"/>')


def track():
    # ">>>>" printed into the ground left of the contact point; fresher near the tyre.
    out = []
    w, h, step = 46, 78, 92
    for k, op in enumerate([0.95, 0.75, 0.55, 0.35]):
        x = cx - 175 - k * step   # tip of the chevron; clear of the tyre's curve
        out.append(f'<polyline points="{x - w},{ground - h / 2:.0f} {x},{ground} '
                   f'{x - w},{ground + h / 2:.0f}" opacity="{op}"/>')
    return "\n    ".join(out)


svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- TimeTrack app icon. Generated by make_icon.py; edit that, not this file. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#3CC6B4"/>
      <stop offset="1" stop-color="#1C7FA0"/>
    </linearGradient>
    <radialGradient id="tyre" cx="0.42" cy="0.38" r="0.7">
      <stop offset="0" stop-color="#3A3F47"/>
      <stop offset="1" stop-color="#16191E"/>
    </radialGradient>
    <linearGradient id="rim" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#E9EEF2"/>
      <stop offset="1" stop-color="#9AA7B2"/>
    </linearGradient>
  </defs>

  <rect width="1024" height="1024" fill="url(#bg)"/>

  <!-- ground -->
  <line x1="0" y1="{ground}" x2="1024" y2="{ground}" stroke="#145E78" stroke-width="6" opacity="0.5"/>

  <!-- track -->
  <g fill="none" stroke="#14232E" stroke-width="24" stroke-linecap="round" stroke-linejoin="round">
    {track()}
  </g>

  <!-- tyre -->
  <circle cx="{cx}" cy="{cy}" r="{R}" fill="url(#tyre)"/>
  <g stroke="#0B0D10" stroke-width="13" stroke-linecap="round">
    {tread_grooves()}
  </g>
  <circle cx="{cx}" cy="{cy}" r="{R - 66}" fill="none" stroke="#2C3138" stroke-width="6"/>

  <!-- rim + clock face -->
  <circle cx="{cx}" cy="{cy}" r="{rim_r}" fill="url(#rim)"/>
  <circle cx="{cx}" cy="{cy}" r="{face_r}" fill="#FBF8F2"/>
  <g stroke="#1B2530" stroke-linecap="round">
    {clock_ticks()}
  </g>
  {hand(300, 100, 22)}
  {hand(60, 150, 14)}
  <circle cx="{cx}" cy="{cy}" r="20" fill="#FF7A2F"/>
</svg>
'''

svg_path = os.path.join(HERE, "AppIcon.svg")
with open(svg_path, "w") as f:
    f.write(svg)

png = subprocess.run(["rsvg-convert", "-w", "1024", "-h", "1024", svg_path],
                     check=True, capture_output=True).stdout
subprocess.run(["convert", "-", "-alpha", "off", PNG], input=png, check=True)
print("wrote", os.path.normpath(svg_path), "and", os.path.normpath(PNG))
